"""Plan-Solve 规划器 prompt 常量。"""

_PLAN_PROMPT = """\
你是一个任务规划专家。请根据用户请求，将任务分解为有序的执行步骤列表。

用户请求：
{user_request}

要求：
- 最多 {max_steps} 个步骤
- 每个步骤是一句简洁的中文描述（不超过 50 字）
- 步骤之间有明确的先后依赖关系
- 只输出 JSON 数组，不要有任何额外内容

输出格式（JSON 数组）：
["步骤1描述", "步骤2描述", ...]
"""

_REPLAN_PROMPT = """\
你是一个任务规划专家。请根据已完成的工作和最新的执行结果，更新剩余步骤计划。

当前已完成步骤序号：{cursor}
原始计划：
{original_plan}

最近执行结果摘要：
{recent_results}

要求：
- 保留已完成的步骤（序号 < {cursor} 的）
- 可以调整、增减 cursor 之后的步骤
- 总步骤数不超过 {max_steps}
- 只输出完整的 JSON 数组（包含所有步骤），不要有任何额外内容

输出格式（JSON 数组，含所有步骤）：
["步骤1描述", "步骤2描述", ...]
"""
